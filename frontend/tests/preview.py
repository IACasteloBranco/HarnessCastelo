"""Exercise the local preview through its real demo login."""

from playwright.sync_api import sync_playwright
from uuid import uuid4
from pathlib import Path
from tempfile import gettempdir


with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1280, "height": 900})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://localhost:18444/")
    page.locator("#employee-code").fill("DEMOCHAT")
    page.locator("#login-password").fill("demo12345")
    page.locator("#login-form button[type=submit]").click()
    page.locator("#chat-view").wait_for(state="visible")
    page.locator("#chat-new").click()
    page.locator("#chat-text").fill("Teste de acesso")
    page.locator("#chat-form button[type=submit]").click()
    page.get_by_text("Prévia simulada: recebi sua mensagem — Teste de acesso").first.wait_for()
    page.locator("#chat-context").click()
    page.locator("#context-scope").select_option("profile")
    page.locator("#profile-text").fill("O colaborador prefere respostas objetivas.")
    page.locator("#profile-form button[type=submit]").click()
    page.locator("#profile-text").fill("")
    page.locator("#context-close").click()
    page.locator("#chat-context").click()
    page.locator("#context-scope").select_option("profile")
    page.wait_for_function("document.querySelector('#profile-text').value === 'O colaborador prefere respostas objetivas.'")
    page.locator("#context-kind").select_option("memory")
    page.locator("#context-content").fill("Prefiro respostas objetivas")
    page.locator("#context-form button[type=submit]").click()
    page.locator(".context-note", has_text="Prefiro respostas objetivas").wait_for()
    page.locator(".context-note-actions button", has_text="Editar").click()
    page.locator("#context-content").fill("Prefiro respostas curtas")
    page.locator("#context-form button[type=submit]").click()
    page.locator(".context-note", has_text="Prefiro respostas curtas").wait_for()
    page.locator("#context-close").click()
    page.locator(".chat-artifact-menu summary").first.click()
    page.locator(".chat-artifact-menu button", has_text="PDF").first.click()
    page.locator("#artifact-dialog").wait_for(state="visible")
    assert page.locator("#artifact-dialog iframe").count() == 1
    with page.expect_download() as generated:
        page.locator("#artifact-dialog-download").click()
    assert generated.value.suggested_filename == "maximus-demo.pdf"
    page.locator("#artifact-dialog-close").click()
    page.locator(".chat-artifact-menu summary").first.click()
    page.locator(".chat-artifact-menu button", has_text="CSV").first.click()
    page.locator("#artifact-dialog-body table").wait_for()
    assert page.locator("#artifact-dialog-body td").first.text_content() == "Teste de acesso"
    page.locator("#artifact-dialog-close").click()
    page.locator("#chat-text").fill("Faça um resumo de teste em PDF para baixar")
    page.locator("#chat-form button[type=submit]").click()
    page.get_by_role("button", name="Visualizar maximus-demo.pdf").nth(1).wait_for()
    page.locator("#chat-new").click()
    page.locator("#chat-attachments").set_input_files({"name": "teste.txt", "mimeType": "text/plain", "buffer": b"arquivo de teste"})
    page.locator("#chat-form button[type=submit]").click()
    page.get_by_role("button", name="Visualizar teste.txt").click()
    page.locator("#artifact-dialog-body pre").get_by_text("arquivo de teste").wait_for()
    with page.expect_download() as downloaded:
        page.locator("#artifact-dialog-download").click()
    assert downloaded.value.suggested_filename == "teste.txt"
    page.locator("#artifact-dialog-close").click()
    project_name = f"Projeto {uuid4().hex[:6]}"
    renamed_project = f"{project_name} novo"
    page.locator("#chat-project-new").click()
    page.locator("#project-name").fill(project_name)
    page.locator("#project-form button[type=submit]").click()
    page.get_by_text(f"Novo chat · {project_name}").wait_for()
    page.screenshot(path=str(Path(gettempdir()) / "maximus-projects-desktop.png"))
    page.set_viewport_size({"width": 390, "height": 844})
    page.locator("#chat-mobile-list").click()
    page.locator("#chat-project-list .chat-project-open", has_text=project_name).wait_for()
    assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
    page.screenshot(path=str(Path(gettempdir()) / "maximus-projects-mobile.png"))
    page.get_by_role("button", name="Fechar conversas").click()
    page.set_viewport_size({"width": 1280, "height": 900})
    page.locator("#chat-text").fill("Mensagem do projeto")
    with page.expect_request("**/api/chat/messages") as project_message:
        page.locator("#chat-form button[type=submit]").click()
    assert project_message.value.post_data_json["project_id"]
    page.get_by_text("Prévia simulada: recebi sua mensagem — Mensagem do projeto").wait_for()
    page.wait_for_function("!state.chat.busy")
    page.locator("#chat-project-general").click()
    page.wait_for_function("state.chat.projectId === null && state.chat.conversations.every(item => item.project_id === null)")
    page.wait_for_function("state.chat.conversationId === state.chat.conversations[0]?.id")
    page.locator("#chat-conversations .chat-conversation-trigger").first.click()
    page.get_by_role("button", name="Mover para projeto").click()
    page.locator(".chat-move-choices").get_by_role("button", name=project_name, exact=True).click()
    page.locator("#chat-project-general").click()
    page.locator("#chat-project-list .chat-project-open", has_text=project_name).click()
    page.wait_for_function("state.chat.conversations.length >= 2")
    page.wait_for_function("state.chat.conversationId === state.chat.conversations[0]?.id")
    page.get_by_role("button", name=f"Opções do projeto {project_name}").click()
    page.get_by_role("button", name="Renomear projeto").click()
    page.locator("#project-name").fill(renamed_project)
    page.locator("#project-form button[type=submit]").click()
    page.get_by_role("button", name=f"Opções do projeto {renamed_project}").click()
    page.once("dialog", lambda dialog: dialog.accept())
    page.get_by_role("button", name="Excluir projeto").click()
    page.get_by_role("button", name=f"Opções do projeto {renamed_project}").wait_for(state="detached")
    page.locator("#chat-project-general").click()
    page.wait_for_function("state.chat.conversations.length >= 2")
    page.locator("#chat-side-user").click()
    page.get_by_text("Configurações", exact=False).wait_for()
    assert page.locator("#chat-side-user").get_attribute("aria-expanded") == "true"
    page.locator("#chat-sidebar-logout").click()
    page.locator("#login-view").wait_for(state="visible")
    page.locator("#employee-code").fill("DEMOGOV")
    page.locator("#login-password").fill("demo12345")
    page.locator("#login-form button[type=submit]").click()
    page.get_by_role("heading", name="Visão de uso").wait_for()
    page.locator("#governance-runs button").first.click()
    page.get_by_text("Esta leitura de conteúdo bruto foi registrada para auditoria.").wait_for()
    assert not errors, errors
    browser.close()
